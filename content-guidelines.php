    <li>Maintain clean heading structure so key sections are easy to scan.</li>
    <li>Connect readers to related resources using meaningful internal links.</li>
    <li>Disclose limitations and verification advice for critical use cases.</li>
  </ul>

  <h2>Thin Content Prevention Rules</h2>
  <p>
    We do not publish pages that contain only short fragments, duplicated boilerplate, or low-effort paraphrasing.
    If a page template is data-heavy by nature, we add contextual sections that explain interpretation,
    common mistakes, and practical use cases relevant to that page type.
    This ensures users receive guidance rather than raw tables alone.
  </p>

  <h2>Readability Standards</h2>
  <ul>
    <li>One clear <code>h1</code> per page, with organized <code>h2</code> and <code>h3</code> subsections.</li>
    <li>Short paragraphs and direct language suitable for mobile reading.</li>
    <li>Avoid unsupported claims and avoid implying official affiliation.</li>
    <li>Prefer examples and action-oriented guidance over vague generalizations.</li>
  </ul>

  <h2>Metadata and Search Integrity</h2>
  <p>
    Titles and descriptions must match page intent.
    We avoid clickbait, overpromising, and misleading snippets.
    Canonical tags and internal links are reviewed to keep indexing behavior predictable and user navigation coherent.
  </p>

  <h2>Programmatic Content Safeguards</h2>
  <p>
    Structured datasets are useful, but data output alone is not enough.
    We therefore include editorial review, contextual writing, and periodic quality checks to prevent a purely programmatic footprint.
    Pages that fail quality checks are revised before promotion.
  </p>

